"""UI string translations — English (default), Latvian, Lithuanian, Estonian."""

from __future__ import annotations

import streamlit as st

_LANG_OPTIONS = {
    "en": "English",
    "lv": "Latviešu",
    "lt": "Lietuvių",
    "et": "Eesti",
}


def current_lang() -> str:
    return st.session_state.get("lang", "en")


def t(key: str, **kwargs: object) -> str:
    """Return translated string for key in the current UI language."""
    lang = current_lang()
    translations = _TRANSLATIONS.get(lang, _TRANSLATIONS["en"])
    text = translations.get(key) or _TRANSLATIONS["en"].get(key) or key
    if kwargs:
        return text.format(**kwargs)
    return text


def render_language_selector() -> None:
    """Render a compact language selector in the sidebar."""
    lang = st.session_state.get("lang", "en")
    options = list(_LANG_OPTIONS.keys())
    labels = list(_LANG_OPTIONS.values())
    idx = options.index(lang) if lang in options else 0
    chosen_label = st.sidebar.selectbox(
        "🌐",
        labels,
        index=idx,
        key="_lang_selector",
        label_visibility="collapsed",
    )
    chosen_code = options[labels.index(chosen_label)]
    if chosen_code != lang:
        st.session_state["lang"] = chosen_code
        st.rerun()


